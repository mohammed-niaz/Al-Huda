// Sets up (or updates) everything Phase 2 needs on Cloudflare. Safe to run again at any time.
// Run by .github/workflows/server.yml — needs these environment variables:
//   CLOUDFLARE_API_TOKEN, CLOUDFLARE_ACCOUNT_ID   from your Cloudflare account
//   ADMIN_CODES     {"Imam Name":"access-code", ...}   (GitHub secret)
//   PAGES_PROJECT   e.g. mesita-alhuda
//   SITE_URL        e.g. https://mesita-alhuda.pages.dev
import { execFileSync } from "node:child_process";
import { writeFileSync, readFileSync, existsSync } from "node:fs";
import { webcrypto as crypto } from "node:crypto";

const ROOT = new URL("..", import.meta.url).pathname;
const SERVER = ROOT + "server/";
const DB_NAME = "masjid", QUEUE = "masjid-push", WORKER = `${process.env.PAGES_PROJECT || "mesita-alhuda"}-push`;
const SITE_URL = (process.env.SITE_URL || "https://mesita-alhuda.pages.dev").replace(/\/$/, "");
const PROJECT = process.env.PAGES_PROJECT || "mesita-alhuda";

const fail = (msg) => { console.log("::error title=Server setup failed::" + String(msg).replace(/\n/g, "%0A")); process.exit(1); };
const step = (msg) => console.log(`\n▶ ${msg}`);
for (const k of ["CLOUDFLARE_API_TOKEN", "CLOUDFLARE_ACCOUNT_ID"]) if (!process.env[k]) fail(`The GitHub secret ${k} is missing. Add it under Settings → Secrets and variables → Actions.`);

function wrangler(args, { json = false, allowFail = false } = {}) {
  try {
    const out = execFileSync(SERVER + "node_modules/.bin/wrangler", args, { cwd: SERVER, encoding: "utf8", stdio: ["ignore", "pipe", "pipe"], env: { ...process.env, CI: "1" } });
    if (!json) return out;
    const start = out.search(/^[\[{]/m);              // skip any warning lines before the JSON
    return JSON.parse(start >= 0 ? out.slice(start) : out);
  } catch (e) {
    if (allowFail) return null;
    const text = `${e.stdout || ""}\n${e.stderr || ""}`.trim().split("\n").filter((l) => l.trim()).slice(-6).join("\n");
    fail(`wrangler ${args.slice(0, 3).join(" ")} failed:\n${text}`);
  }
}
const sqlStr = (s) => `'${String(s).replace(/'/g, "''")}'`;
const writeWorkerConfig = (dbId) => writeFileSync(SERVER + "wrangler.toml", `# Generated by scripts/setup-server.mjs — do not edit
name = "${WORKER}"
main = "worker.js"
compatibility_date = "2026-06-01"
workers_dev = false
preview_urls = false

[triggers]
crons = ["* * * * *"]

[[d1_databases]]
binding = "DB"
database_name = "${DB_NAME}"
database_id = "${dbId}"

[[queues.producers]]
binding = "PUSHQ"
queue = "${QUEUE}"

[[queues.consumers]]
queue = "${QUEUE}"
max_batch_size = 1
max_retries = 2

[vars]
SITE_URL = "${SITE_URL}"
`);

// 1. database
step("Database");
let db = (wrangler(["d1", "list", "--json"], { json: true }) || []).find((d) => d.name === DB_NAME);
if (!db) {
  wrangler(["d1", "create", DB_NAME]);
  db = (wrangler(["d1", "list", "--json"], { json: true }) || []).find((d) => d.name === DB_NAME);
  if (!db) fail("The database was created but could not be found afterwards. Run the job again.");
  console.log(`Created database ${DB_NAME}`);
} else console.log(`Database ${DB_NAME} already exists`);
const dbId = db.uuid || db.id || db.database_id;
writeWorkerConfig(dbId);
wrangler(["d1", "execute", DB_NAME, "--remote", "--file=schema.sql", "-y"]);
console.log("Tables are ready");

const query = (sql) => {
  const res = wrangler(["d1", "execute", DB_NAME, "--remote", "--json", "--command", sql], { json: true });
  return (Array.isArray(res) ? res[0] : res).results || [];
};

// 2. queue
step("Queue");
const q = wrangler(["queues", "create", QUEUE], { allowFail: true });
console.log(q ? `Created queue ${QUEUE}` : `Queue ${QUEUE} already exists (or could not be created; the deploy step will tell)`);

// 3. notification keys (made once; changing them would sign everyone out of alerts)
step("Notification keys");
const haveKeys = query("SELECT key FROM kv WHERE key = 'vapid'").length > 0;
if (!haveKeys) {
  const kp = await crypto.subtle.generateKey({ name: "ECDSA", namedCurve: "P-256" }, true, ["sign", "verify"]);
  const publicKey = Buffer.from(await crypto.subtle.exportKey("raw", kp.publicKey)).toString("base64url");
  const privateJWK = await crypto.subtle.exportKey("jwk", kp.privateKey);
  const value = JSON.stringify({ publicKey, privateJWK: { kty: privateJWK.kty, crv: privateJWK.crv, x: privateJWK.x, y: privateJWK.y, d: privateJWK.d }, subject: SITE_URL });
  query(`INSERT INTO kv (key, value) VALUES ('vapid', ${sqlStr(value)})`);
  console.log("Created new notification keys");
} else console.log("Notification keys already exist (kept)");

// 4. imam access codes
step("Imam access codes");
let codes = {};
try { codes = JSON.parse(process.env.ADMIN_CODES || "{}"); } catch (e) { fail('ADMIN_CODES must look like {"Imam Yusuf":"noor-sabr-1234-huda"} (straight double quotes).'); }
const names = Object.keys(codes).filter((n) => String(codes[n]).length >= 8);
if (!names.length) fail('Add the GitHub secret ADMIN_CODES, e.g. {"Imam Yusuf":"noor-sabr-1234-huda"}. Each code needs at least 8 characters.');
let salt = query("SELECT value FROM kv WHERE key = 'admin_salt'")[0];
salt = salt ? JSON.parse(salt.value) : Buffer.from(crypto.getRandomValues(new Uint8Array(16))).toString("hex");
const hash = async (code) => Buffer.from(await crypto.subtle.digest("SHA-256", new TextEncoder().encode(`${salt}:${code}`))).toString("hex");
const stmts = [`INSERT OR REPLACE INTO kv (key, value) VALUES ('admin_salt', ${sqlStr(JSON.stringify(salt))})`, "DELETE FROM admins"];
for (const n of names) stmts.push(`INSERT INTO admins (name, hash) VALUES (${sqlStr(n.slice(0, 60))}, ${sqlStr(await hash(String(codes[n])))})`);
writeFileSync(SERVER + ".admins.sql", stmts.join(";\n") + ";\n");
wrangler(["d1", "execute", DB_NAME, "--remote", "--file=.admins.sql", "-y"]);
writeFileSync(SERVER + ".admins.sql", "");
console.log(`Access codes saved for: ${names.join(", ")}`);

// 5. notification worker
step("Notification worker");
wrangler(["deploy"]);
console.log(`Deployed ${WORKER} (runs every minute, no public address)`);

// 6. connect the Pages site to the database and the queue
step("Pages settings");
const pagesToml = `# Generated by scripts/setup-server.mjs — connects the site's /api to the database and queue.
# Cloudflare Pages reads this file on every deploy. Re-run "Set up server" instead of editing it.
name = "${PROJECT}"
pages_build_output_dir = "."
compatibility_date = "2026-06-01"

[[d1_databases]]
binding = "DB"
database_name = "${DB_NAME}"
database_id = "${dbId}"

[[queues.producers]]
binding = "PUSHQ"
queue = "${QUEUE}"
`;
const tomlPath = ROOT + "wrangler.toml";
const changed = !existsSync(tomlPath) || readFileSync(tomlPath, "utf8") !== pagesToml;
writeFileSync(tomlPath, pagesToml);
console.log(changed ? "wrangler.toml updated — it will be committed and Pages will redeploy" : "wrangler.toml already up to date");
console.log("\n✔ Server is set up.");
